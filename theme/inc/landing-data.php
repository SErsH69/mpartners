/**
 * Значение из контента хаба.
 *
 * @param string $path    Путь вида `hero.title`.
 * @param mixed  $default Запасное значение.
 * @return mixed
 */
function mp_landings( $path = '', $default = '' ) {
	if ( function_exists( 'mp_content_get' ) ) {
		return mp_content_get( 'landings', $path, $default );
	}

	$value = mp_landings_data();

	foreach ( array_filter( explode( '.', $path ) ) as $key ) {
		if ( ! is_array( $value ) || ! array_key_exists( $key, $value ) ) {
			return $default;
		}

		$value = $value[ $key ];
	}

	return $value;
}
