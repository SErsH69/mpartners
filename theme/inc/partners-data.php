/**
 * Значение из контента страницы.
 *
 * @param string $path    Путь вида `invite.title`.
 * @param mixed  $default Запасное значение.
 * @return mixed
 */
function mp_partners( $path = '', $default = '' ) {
	if ( function_exists( 'mp_content_get' ) ) {
		$saved = mp_content_get( 'partners', $path, null );

		if ( null !== $saved && '' !== $saved && [] !== $saved ) {
			return $saved;
		}
	}

	$value = mp_partners_data();

	foreach ( array_filter( explode( '.', $path ) ) as $key ) {
		if ( ! is_array( $value ) || ! array_key_exists( $key, $value ) ) {
			return $default;
		}

		$value = $value[ $key ];
	}

	return $value;
}
