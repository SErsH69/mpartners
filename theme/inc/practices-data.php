/**
 * Read a value from the page data by dot path.
 *
 * @param string $path     Dot path, e.g. 'form.fields.name'.
 * @param mixed  $fallback Returned when the path is missing.
 * @return mixed
 */
function mp_practice( $path, $fallback = '' ) {
	if ( function_exists( 'mp_content_get' ) ) {
		return mp_content_get( 'practices', $path, $fallback );
	}

	$value = mp_practices_data();

	foreach ( explode( '.', $path ) as $key ) {
		if ( ! is_array( $value ) || ! array_key_exists( $key, $value ) ) {
			return $fallback;
		}

		$value = $value[ $key ];
	}

	return $value;
}
