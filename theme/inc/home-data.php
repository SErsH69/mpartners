/**
 * Fetch a branch of the front page data by dot path.
 *
 * @param string $path    Dot separated path, e.g. `hero.title`.
 * @param mixed  $default Fallback value.
 * @return mixed
 */
function mp_data( $path, $default = null ) {
	$value = mp_home_data();

	foreach ( explode( '.', $path ) as $key ) {
		if ( ! is_array( $value ) || ! array_key_exists( $key, $value ) ) {
			return $default;
		}

		$value = $value[ $key ];
	}

	return $value;
}

/**
 * URL of an image copied to the theme `dist/img` folder by webpack.
 *
 * @param string $name Base file name without extension.
 * @param string $ext  Extension.
 * @return string
 */
function mp_img( $name, $ext = 'png' ) {
	return get_template_directory_uri() . '/dist/img/figma/' . $name . '.' . $ext;
}

/**
 * Print a multiline string with `<br>` separators, escaping each line.
 *
 * @param string $text Raw text.
 */
function mp_nl2br( $text ) {
	$lines = array_map( 'esc_html', explode( "\n", (string) $text ) );

	echo implode( '<br>', $lines ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- Escaped above.
}
