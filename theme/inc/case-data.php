/**
 * Read a value from the page data by dot path.
 *
 * @param string $path     Dot path, e.g. 'hero.title'.
 * @param mixed  $fallback Returned when the path is missing.
 * @return mixed
 */
function mp_case( $path, $fallback = '' ) {
	if ( function_exists( 'mp_content_get' ) ) {
		return mp_content_get( 'case', $path, $fallback );
	}

	$value = mp_case_data();

	foreach ( explode( '.', $path ) as $key ) {
		if ( ! is_array( $value ) || ! array_key_exists( $key, $value ) ) {
			return $fallback;
		}

		$value = $value[ $key ];
	}

	return $value;
}
