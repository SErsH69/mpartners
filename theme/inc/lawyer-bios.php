const MP_LAWYER_BIOS_VERSION = '1';

/**
 * Переносит биографии в карточки адвокатов.
 *
 * Заодно снимает метку демо-карточки: теперь у каждого адвоката своя
 * специализация и своя биография, рыба из макета больше не нужна.
 */
function mp_seed_lawyer_bios() {
	if ( get_option( 'mp_lawyer_bios_version' ) === MP_LAWYER_BIOS_VERSION ) {
		return;
	}

	if ( ! function_exists( 'update_field' ) || ! function_exists( 'mp_find_lawyer' ) ) {
		return;
	}

	$bios = mp_lawyer_bios();

	foreach ( mp_lawyer_people() as $person ) {
		$id = mp_find_lawyer( $person );

		if ( ! $id ) {
			continue;
		}

		delete_post_meta( $id, '_mp_lawyer_demo' );

		if ( ! isset( $bios[ $person['name'] ] ) ) {
			continue;
		}

		$bio = $bios[ $person['name'] ];

		if ( ! empty( $bio['spec']['items'] ) || ! empty( $bio['spec']['note'] ) ) {
			update_field( 'lawyer_spec', mp_content_to_acf( $bio['spec'] ), $id );
		}

		if ( ! empty( $bio['timeline'] ) ) {
			update_field( 'lawyer_timeline', mp_content_to_acf( $bio['timeline'] ), $id );
		}
	}

	update_option( 'mp_lawyer_bios_version', MP_LAWYER_BIOS_VERSION );
}
add_action( 'init', 'mp_seed_lawyer_bios', 23 );
