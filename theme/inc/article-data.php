/**
 * Read a value from the article data by dot path.
 *
 * @param string $path     Dot path.
 * @param mixed  $fallback Returned when the path is missing.
 * @return mixed
 */
function mp_article( $path, $fallback = '' ) {
	if ( function_exists( 'mp_content_get' ) ) {
		return mp_content_get( 'article', $path, $fallback );
	}

	$value = mp_article_data();

	foreach ( explode( '.', $path ) as $key ) {
		if ( ! is_array( $value ) || ! array_key_exists( $key, $value ) ) {
			return $fallback;
		}

		$value = $value[ $key ];
	}

	return $value;
}
